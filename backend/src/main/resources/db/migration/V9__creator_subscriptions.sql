CREATE TABLE creator_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscriber_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    creator_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_creator_subscriptions_pair UNIQUE (subscriber_id, creator_id),
    CONSTRAINT ck_creator_subscriptions_distinct CHECK (subscriber_id <> creator_id)
);

CREATE INDEX idx_creator_subscriptions_order
    ON creator_subscriptions (subscriber_id, created_at DESC, creator_id);
CREATE INDEX idx_creator_subscriptions_creator ON creator_subscriptions (creator_id);
